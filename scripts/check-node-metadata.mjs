import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createServer } from 'vite';

const server = await createServer({ server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
try {
  const { NodeMetadataSchema } = await server.ssrLoadModule('/src/utils/atlas/nodeMetadata.ts');
  const metadata = { hemisphere: 'left', details: { volume: 12 }, scores: [1, 2] };
  assert.deepEqual(NodeMetadataSchema.parse({ tags: { hemisphere: 'left' }, metadata }), metadata);
  assert.throws(() => NodeMetadataSchema.parse({ tags: { hemisphere: 'right' }, metadata }));
  assert.throws(() => NodeMetadataSchema.parse({ metadata: [] }));
  const { validateAtlasDefinition, getCommonNodeFields } = await server.ssrLoadModule('/src/utils/atlas/atlasDefinition.ts');
  const raw = { id: 'test', name: 'Test', nodes: [{ id: 'a', atlasId: 'a', index: 0, name: 'A', label: 'A', metadata }] };
  const result = validateAtlasDefinition(raw);
  assert.ok(result.ok);
  assert.deepEqual(result.atlas.nodes[0].metadata, metadata);
  assert.deepEqual(getCommonNodeFields(result.atlas), ['hemisphere']);
  assert.ok(!Object.hasOwn(result.atlas.nodes[0], 'tags'));
  const legacy = validateAtlasDefinition({ ...raw, nodes: [{ ...raw.nodes[0], metadata: { details: metadata.details }, tags: { hemisphere: 'left' } }] });
  assert.ok(legacy.ok);
  assert.equal(legacy.atlas.nodes[0].metadata.hemisphere, 'left');
  const { normalizeNodes } = await server.ssrLoadModule('/src/utils/import/normalizeNodes.ts');
  const errors = [];
  const normalized = normalizeNodes({ nodeMetadataPayload: raw.nodes, networks: [{ data: [[0]] }], errors, inference: { generatedNodeIds: [] } });
  assert.deepEqual(errors, []);
  assert.deepEqual(normalized[0].metadata, metadata);
  assert.ok(!Object.hasOwn(normalized[0], 'tags'));
  const { buildNodeGroupsFromMetadata } = await server.ssrLoadModule('/src/networkDerivation/aggregation/nodeGroupAggregation.ts');
  const groups = buildNodeGroupsFromMetadata({ nodeSet: { nodes: normalized }, fields: ['hemisphere'], activeNodeIds: new Set(['a']), missingTagPolicy: 'unknown_group' });
  assert.equal(groups.groups[0].criteria.hemisphere, 'left');
  const { loadNetworkImportFromBytes } = await server.ssrLoadModule('/src/utils/import/loadNetworkImport.ts');
  const bytes = readFileSync('public/examples/test_data.zip');
  const imported = await loadNetworkImportFromBytes('demo.zip', bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
  assert.deepEqual(imported.normalized.issues.errors, []);
  assert.equal(imported.dataset.nodeSet.nodes[0].metadata.hemisphere, 'left');
  assert.ok(imported.dataset.nodeSet.nodes.every(node => node.mesh_points?.length >= 4));
  assert.ok(imported.dataset.nodeSet.nodes.every(node => !Object.hasOwn(node, 'tags')));
  const { buildNodeGroupingColorById } = await server.ssrLoadModule('/src/utils/groupingColoring.ts');
  const { buildRows } = await server.ssrLoadModule('/src/components/selected-links/selectedLinksPanel.utils.ts');
  const { D3_GROUPING_PALETTES } = await server.ssrLoadModule('/src/config/groupingPalettes.ts');
  const colorAtlas = { ...result.atlas, nodes: [result.atlas.nodes[0], { ...result.atlas.nodes[0], id: 'b', atlasId: 'b', metadata: { hemisphere: 'right' } }] };
  const colors = buildNodeGroupingColorById({ atlasDefinition: colorAtlas, groupingFields: ['hemisphere'], colorPalette: Object.keys(D3_GROUPING_PALETTES)[0] });
  const [row] = buildRows({ links: [{ id: 'a::b', rowId: 'a', colId: 'b', rowLabel: 'Same label', colLabel: 'Same label', sources: [] }], selectedNetworkIds: [], networkLookup: {}, atlasIndex: new Map() });
  assert.equal(row.rowId, 'a');
  assert.equal(row.colId, 'b');
  assert.ok(colors[row.rowId]);
  assert.ok(colors[row.colId]);
  assert.notEqual(colors[row.rowId], colors[row.colId]);
  console.log('Node metadata checks passed: import, legacy conversion, conflict validation, nested values and grouping.');
} finally {
  await server.close();
}
