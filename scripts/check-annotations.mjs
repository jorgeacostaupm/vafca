import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createServer } from 'vite';

const server = await createServer({ server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
try {
  const load = path => server.ssrLoadModule(`/src/${path}.ts`);
  const actions = await load('store/slices/visualizationUi/visualizationUiSlice');
  const selectors = await load('store/slices/visualizationUi/annotationSelectors');
  const { combinedReducer } = await load('store/rootReducer');
  const { snapshotWorkspace, prepareWorkspace } = await load('workspace/state');
  const { setDataset } = await load('store/slices/dataset/datasetSlice');
  const { loadNetworkImportFromBytes } = await load('utils/import/loadNetworkImport');
  const { createNetworkCompoundId } = await load('utils/networkMetadata');
  const bytes = readFileSync('public/examples/complete_example.zip');
  const { dataset } = await loadNetworkImportFromBytes('example.zip', bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
  let state = combinedReducer(undefined, { type: '@@init' });
  const dispatch = action => typeof action === 'function' ? action(dispatch, () => state, undefined) : (state = combinedReducer(state, action));
  dispatch(setDataset({ content: dataset }));
  const current = () => selectors.selectCurrentAnnotation(state);
  assert.equal(current().name, 'Annotation 1');
  const defaultColor = current().color;
  const net = dataset.networks[0];
  const [a, b] = net.nodeIds;
  dispatch(actions.toggleAnnotationNode({ id: a, label: 'A' }));
  dispatch(actions.setAtlasNodeIds([a, a, 'unknown']));
  assert.deepEqual(current().atlasNodeIds, [a], 'Viewer node selection validates and deduplicates IDs');
  dispatch(actions.toggleAnnotationNode({ id: a, label: 'A' }));
  assert.deepEqual(current().atlasNodeIds, [], 'Removing a node clears its viewer selection');

  const link = { id: `${a}::${b}`, rowId: a, colId: b, rowLabel: 'A', colLabel: 'B', sources: [{ compoundId: createNetworkCompoundId(net), networkLabel: 'Network', value: NaN }] };
  dispatch(actions.addSelectedLink(link));
  dispatch(actions.toggleAnnotationNode({ id: a, label: 'A' }));
  dispatch(actions.setAtlasLinkIds([link.id]));
  dispatch(actions.createNewAnnotation({ name: ' Second ', description: 'Notes', color: '#123456' }));
  assert.equal(current().name, 'Second');
  assert.equal(current().description, 'Notes');
  assert.equal(current().color, '#123456');
  const secondId = current().id;
  assert.notEqual(secondId, 'default');
  assert.equal(current().selectedLinks.length, 0);
  dispatch(actions.updateAnnotation({ id: secondId, name: 'Second', description: 'Notes', color: '#123456' }));
  dispatch(actions.addSelectedLinks([link, { ...link, id: `${b}::${a}`, rowId: b, colId: a }]));
  dispatch(actions.toggleAnnotationNode({ id: a, label: 'A' }));
  assert.equal(current().selectedLinks.length, 1, 'Undirected links cannot be duplicated in a list');
  let colors = selectors.selectAnnotationColors(state);
  assert.equal(colors.links[link.id], '#ff0000');
  assert.equal(colors.links[`${b}::${a}`], '#ff0000');
  assert.equal(colors.nodes[a], '#ff0000');
  dispatch(actions.setAnnotationOverlapColor('#654321'));
  assert.equal(selectors.selectAnnotationColors(state).nodes[a], '#654321');
  dispatch(actions.updateAnnotation({ id: secondId, active: false }));
  assert.equal(selectors.selectAnnotationColors(state).links[link.id], defaultColor);
  assert.equal(current().selectedLinks.length, 1, 'Hiding preserves data');
  dispatch(actions.updateAnnotation({ id: 'default', active: false }));
  assert.deepEqual(selectors.selectAnnotationColors(state), { links: {}, nodes: {} });
  dispatch(actions.updateAnnotation({ id: secondId, active: true }));
  assert.equal(selectors.selectAnnotationColors(state).links[link.id], '#123456');
  dispatch(actions.updateAnnotation({ id: secondId, name: ' ', color: 'invalid' }));
  assert.equal(current().name, 'Second');
  assert.equal(current().color, '#123456');
  dispatch(actions.selectAnnotation('unknown'));
  assert.equal(current().id, secondId);

  dispatch(actions.selectAnnotation('default'));
  dispatch(actions.addSelectedLink({ ...link, id: `${b}::${b}`, rowId: b, colId: b }));
  assert.equal(current().selectedLinks.length, 1, 'Browsing tabs does not change the destination');
  assert.equal(state.visualizationUi.annotations.find(item => item.id === secondId).selectedLinks.length, 2);
  dispatch(actions.removeSelectedLinks({ annotationId: secondId, ids: [`${b}::${b}`] }));
  dispatch(actions.toggleActiveAnnotation(secondId));
  dispatch(actions.addSelectedLink({ ...link, id: `${b}::${b}`, rowId: b, colId: b }));
  assert.equal(state.visualizationUi.annotations.find(item => item.id === secondId).selectedLinks.length, 1, 'No active annotation means no new links');
  const inactiveSnapshot = snapshotWorkspace(state);
  assert.equal(prepareWorkspace(inactiveSnapshot).visualizationUi.activeAnnotationId, null);
  dispatch(actions.toggleActiveAnnotation(secondId));
  dispatch(actions.selectAnnotation(secondId));
  if (!current().nodes.some(node => node.id === a)) dispatch(actions.toggleAnnotationNode({ id: a, label: 'A', annotationId: secondId }));
  dispatch(actions.setAtlasNodeIds([a]));
  const saved = snapshotWorkspace(state);
  const restored = prepareWorkspace(saved);
  assert.deepEqual(selectors.selectCurrentAnnotation(restored).atlasNodeIds, [a], 'Viewer node selection survives workspace restoration');
  const previousSession = structuredClone(saved);
  for (const annotation of previousSession.session.visualizationUi.annotations) delete annotation.atlasNodeIds;
  assert.deepEqual(selectors.selectCurrentAnnotation(prepareWorkspace(previousSession)).atlasNodeIds, [], 'Older sessions start with no viewer nodes selected');
  assert.deepEqual(snapshotWorkspace(restored).session.visualizationUi, saved.session.visualizationUi, 'Annotations round trip including hidden lists and metadata');
  assert.ok(Number.isNaN(selectors.selectSelectedLinks(restored)[0].sources[0].value));
  assert.equal(selectors.selectSelectedLinksById(restored)[link.id].id, link.id);
  const legacy = structuredClone(saved);
  const ui = legacy.session.visualizationUi;
  ui.selectedLinks = ui.annotations[0].selectedLinks;
  ui.atlasLinkIds = ui.annotations[0].atlasLinkIds;
  delete ui.annotations; delete ui.currentAnnotationId; delete ui.activeAnnotationId; delete ui.annotationOverlapColor;
  const migrated = prepareWorkspace(legacy);
  assert.equal(selectors.selectCurrentAnnotation(migrated).name, 'Annotation 1');
  assert.equal(selectors.selectSelectedLinks(migrated)[0].id, link.id);
  const invalid = structuredClone(saved);
  invalid.session.visualizationUi.currentAnnotationId = 'missing';
  assert.throws(() => prepareWorkspace(invalid), /Unknown current annotation/);
  dispatch(actions.removeSelectedLink(link.id));
  assert.equal(current().selectedLinks.length, 0);
  dispatch(actions.selectAnnotation('default'));
  assert.equal(current().selectedLinks.length, 1, 'Removal affects only the target list');
  dispatch(actions.pruneSelectedLinksForDisabledCatalogItem({ invalidCompoundIds: [link.sources[0].compoundId] }));
  assert.ok(state.visualizationUi.annotations.every(item => item.selectedLinks.length === 0));
  dispatch(actions.removeAnnotation('default'));
  assert.equal(current().id, secondId);
  dispatch(actions.removeAnnotation(secondId));
  assert.equal(state.visualizationUi.annotations.length, 1, 'There must always be a target annotation');
  // Deferred chunks keep the original destination after the user selects another tab.
  dispatch(actions.createNewAnnotation());
  const brushTargetId = current().id;
  dispatch(actions.addSelectedLinks({ annotationId: brushTargetId, links: [link] }));
  dispatch(actions.selectAnnotation(secondId));
  dispatch(actions.addSelectedLinks({ annotationId: brushTargetId, links: [{ ...link, id: `${b}::${b}`, rowId: b, colId: b }] }));
  assert.equal(current().selectedLinks.length, 0);
  assert.equal(state.visualizationUi.annotations.find(item => item.id === brushTargetId).selectedLinks.length, 2);
  dispatch(actions.removeSelectedLinks({ annotationId: brushTargetId, ids: [link.id] }));
  assert.equal(state.visualizationUi.annotations.find(item => item.id === brushTargetId).selectedLinks.length, 1);
  dispatch(actions.removeAnnotation(brushTargetId));
  dispatch(actions.addSelectedLinks({ annotationId: brushTargetId, links: [link] }));
  dispatch(actions.removeSelectedLinks({ annotationId: brushTargetId, ids: [link.id] }));
  assert.equal(current().selectedLinks.length, 0, 'Late chunks for a deleted annotation never modify its replacement');
  const { annotateMatrixBrush } = await load('store/slices/visualizationUi/thunks/annotateMatrixBrush');
  const { MATRIX_BRUSH_LINK_DISPATCH_CHUNK_SIZE: chunkSize } = await load('config/ui');
  dispatch(actions.createNewAnnotation());
  const asyncTarget = current().id;
  const cells = Array.from({ length: chunkSize + 1 }, (_, i) => ({ row: 0, col: i, rowLabel: a, colLabel: `node-${i}`, value: i }));
  const brush = { annotationId: asyncTarget, cells, labelOrder: [a, ...cells.map(cell => cell.colLabel)], compoundId: link.sources[0].compoundId, networkLabel: 'Test' };
  const adding = dispatch(annotateMatrixBrush({ ...brush, mode: 'add' }));
  dispatch(actions.selectAnnotation(secondId));
  await adding.unwrap();
  assert.equal(current().selectedLinks.length, 0);
  assert.equal(state.visualizationUi.annotations.find(item => item.id === asyncTarget).selectedLinks.length, cells.length, 'All deferred chunks reach the original annotation');
  await dispatch(annotateMatrixBrush({ ...brush, mode: 'remove' })).unwrap();
  assert.equal(state.visualizationUi.annotations.find(item => item.id === asyncTarget).selectedLinks.length, 0);
  const interrupted = dispatch(annotateMatrixBrush({ ...brush, mode: 'add' }));
  dispatch(actions.removeAnnotation(asyncTarget));
  await interrupted.unwrap();
  assert.equal(current().selectedLinks.length, 0, 'Deleting the destination safely stops a running brush');
  console.log('Annotations: isolation, overlap colors, visibility, validation, pruning, workspace round trip and legacy migration passed.');
} finally { await server.close(); }
