import assert from 'node:assert/strict';
import { isDeepStrictEqual } from 'node:util';
import { readFileSync } from 'node:fs';
import { createServer } from 'vite';

const server = await createServer({ server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
try {
  const load = path => server.ssrLoadModule(`/src/${path}.ts`);
  await load('store/slices/visualizationUi/visualizationUiSlice');
  const { combinedReducer, rootReducer } = await load('store/rootReducer');
  const { setDataset } = await load('store/slices/dataset/datasetSlice');
  const { setUploadedAtlas } = await load('store/slices/atlasDefinition/atlasDefinitionSlice');
  const { setAtlasLabels, buildAtlasState } = await load('store/slices/atlasUi/atlasUiSlice');
  const { buildAtlasSourceFromNodeSet } = await load('utils/atlas/nodeDerivedAtlas');
  const { getDatasetNodeOrder } = await load('utils/datasetAccessors');
  const { loadNetworkImportFromBytes } = await load('utils/import/loadNetworkImport');
  const { snapshotWorkspace, prepareWorkspace } = await load('workspace/state');
  const { encodeWorkspace, decodeWorkspace } = await load('workspace/archive');
  const { restoreWorkspace } = await load('workspace/actions');
  const { createNetworkCompoundId } = await load('utils/networkMetadata');
  const bytes = readFileSync('public/examples/complete_example.zip');
  const { dataset } = await loadNetworkImportFromBytes('example.zip', bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
  assert.ok(dataset.networks.length);
  let state = combinedReducer(undefined, { type: '@@init' });
  state = combinedReducer(state, setDataset({ content: dataset }));
  state = combinedReducer(state, setUploadedAtlas(buildAtlasSourceFromNodeSet(dataset.nodeSet, 'example')));
  state = combinedReducer(state, setAtlasLabels(buildAtlasState(getDatasetNodeOrder({ content: dataset }))));
  state = structuredClone(state);
  const net = dataset.networks[0];
  const [a, b] = net.nodeIds;
  const compoundId = createNetworkCompoundId(net);
  state.visualizationUi.annotations[0].selectedLinks = [{ id: `${a}::${b}`, rowId: a, colId: b, rowLabel: 'A', colLabel: 'B', sources: [{ compoundId, networkLabel: 'Test', value: 0.5 }] }];
  state.visualizationUi.annotations[0].atlasLinkIds = [`${a}::${b}`];
  state.visualizationUi.atlasPanel.spatialMode = 'points';
  state.visualizationUi.atlasPanel.is3dAvailable = true;
  state.workspaceUi.activeSection = 'derive';
  state.workspaceUi.selectedNetworkIds = [compoundId];
  state.workspaceUi.cameras.links = { position: [0.2, 0.8, 0.3], target: [0, 0, 0], zoom: 1 };
  state.atlasUi.colorFields = ['hemisphere'];
  state.atlasUi.labelsById[b].enabled = false;
  state.networkVisualization.viewsOrder = ['saved-view'];
  state.networkVisualization.viewsById['saved-view'] = { id: 'saved-view', type: 'matrix', compoundId, label: 'Saved matrix', measureId: net.measureId, statisticId: net.statisticId, status: 'ready' };
  state.networkVisualization.matrixSettingsByViewId['saved-view'] = { zoomHistory: [null, { rows: [a], cols: [b] }], zoomIndex: 1, brushMode: 'selectLinks', statRange: { negative: [-1, 0], positive: [0, 1] } };
  state.networkLayout.layout = [{ i: 'saved-view', x: 0, y: 0, w: 6, h: 4 }];
  state.networkFilters.activeNetworkFilter = {
    uiRangeMode: 'view_observed', root: { type: 'group', id: 'filter', operator: 'AND', children: [{ type: 'rule', id: 'rule', networkId: net.id, operator: 'gte', min: 0, max: null, includeMin: true, includeMax: true }] },
  };
  const rankingQuery = { ...state.rankings.currentQuery, target: 'links', mode: 'singleNetwork', networkId: net.id, measureId: net.measureId, statisticId: net.statisticId, metric: 'meanValue' };
  state.rankings.resultsOrder = ['ranking-1'];
  state.rankings.resultsById['ranking-1'] = { id: 'ranking-1', query: rankingQuery, rows: [], totalEligibleItems: 0, createdAt: '2026-01-01' };
  state.rankings.nextResultSeq = 2;
  state.networkVisualization.viewsOrder.push('temporary-view');
  state.networkVisualization.viewsById['temporary-view'] = { id: 'temporary-view', type: 'circular', compoundId: '', temporaryNetworkId: 'temporary-network', coordinationDisabled: true, label: 'Groups', measureId: net.measureId, statisticId: net.statisticId, status: 'ready' };
  state.networkVisualization.temporaryNetworksById['temporary-network'] = { id: 'temporary-network', sourceViewId: 'saved-view', sourceNetworkLabel: 'Source', label: 'Groups', measureId: net.measureId, statisticId: net.statisticId, data: [[NaN, 0.5], [0.5, NaN]], rowLabels: ['g1', 'g2'], colLabels: ['g1', 'g2'], symmetric: true, groups: [{ id: 'g1', label: 'Left', criteria: { hemisphere: 'left' }, nodeIds: [a] }, { id: 'g2', label: 'Right', criteria: { hemisphere: 'right' }, nodeIds: [b] }], labelNames: { g1: 'Left', g2: 'Right' }, labelTitles: {}, labelAcronyms: {}, nodeColors: {}, createdAt: '2026-01-01' };
  const payload = snapshotWorkspace(state);
  const prepared = prepareWorkspace(payload);
  const archive = await encodeWorkspace(snapshotWorkspace(prepared));
  const asDataset = await loadNetworkImportFromBytes('workspace.zip', Uint8Array.from(archive).buffer);
  assert.deepEqual(asDataset.normalized.issues.errors, []);
  assert.deepEqual(asDataset.dataset.networks.map(network => network.id), dataset.networks.map(network => network.id));
  const restored = prepareWorkspace(await decodeWorkspace(archive));
  assert.ok(isDeepStrictEqual(JSON.parse(JSON.stringify(snapshotWorkspace(restored))), JSON.parse(JSON.stringify(snapshotWorkspace(prepared)))), 'Persisted workspace content differs after round trip');
  assert.deepEqual(restored.visualizationUi.annotations[0].selectedLinksById[`${a}::${b}`], state.visualizationUi.annotations[0].selectedLinks[0]);
  assert.equal(restored.workspaceUi.activeSection, 'derive');
  assert.deepEqual(restored.dataset.networks.ids, state.dataset.networks.ids);
  assert.ok(isDeepStrictEqual(JSON.parse(JSON.stringify(restored.atlasDefinition.uploaded.atlas.nodes)), JSON.parse(JSON.stringify(state.atlasDefinition.uploaded.atlas.nodes))));
  assert.deepEqual(restored.workspaceUi, state.workspaceUi);
  assert.equal(restored.atlasUi.labelsById[b].enabled, false);
  assert.ok(Number.isNaN(restored.networkVisualization.temporaryNetworksById['temporary-network'].data[0][0]));
  assert.ok(restored.networkFilters.activeEdgeMask);
  assert.ok(restored.rankings.resultsById['ranking-1'].rows.length > 0);
  assert.ok(!Object.hasOwn(restored.dataset.networks.entities, 'temporary-network'));
  assert.equal(rootReducer(state, restoreWorkspace(restored)), restored);
  const invalid = structuredClone(payload);
  invalid.session.networkVisualization.viewsById['saved-view'].compoundId = 'missing';
  assert.throws(() => prepareWorkspace(invalid), /Missing network/);
  const malformed = structuredClone(payload);
  malformed.session.visualizationUi.annotations[0].selectedLinks[0].rowId = 'unknown';
  assert.throws(() => prepareWorkspace(malformed), /unknown node/);
  await assert.rejects(() => decodeWorkspace(new Uint8Array([1,2,3])));
  const badFilter = structuredClone(payload);
  badFilter.session.networkFilters.activeNetworkFilter.root.children[0].networkId = 'missing';
  assert.throws(() => prepareWorkspace(badFilter));
  const badMatrix = structuredClone(payload);
  badMatrix.dataset.networks[0].data.values = [[1]];
  assert.throws(() => prepareWorkspace(badMatrix), /matrix dimensions/);
  const { openWorkspace } = await load('workspace/thunks');
  const dispatched = [];
  const rejected = await openWorkspace({ file: new File([new Uint8Array([1,2,3])], 'bad.zip') })(action => dispatched.push(action), () => state, undefined);
  assert.equal(rejected.meta.requestStatus, 'rejected');
  assert.ok(!dispatched.some(action => restoreWorkspace.match(action)));
  const { unzipSync, zipSync, strToU8 } = await import('fflate');
  const entries = unzipSync(archive);
  assert.ok(!entries['dataset.json'] && !entries['manifest.json']);
  assert.ok(entries['matrices.json'] && entries['rois.json'] && entries['catalogs/dimensions.json']);
  const corrupted = { ...entries, 'matrices.json': strToU8(JSON.stringify([{ id: 'invalid' }])) };
  await assert.rejects(() => decodeWorkspace(zipSync(corrupted)));

  const sessionFile = JSON.parse(new TextDecoder().decode(entries['session.json']));
  entries['session.json'] = strToU8(JSON.stringify({ ...sessionFile, formatVersion: 'future-version' }));
  await assert.rejects(() => decodeWorkspace(zipSync(entries)), /Unsupported/);
  const empty = combinedReducer(undefined, { type: '@@init' });
  const emptyRestored = prepareWorkspace(await decodeWorkspace(await encodeWorkspace(snapshotWorkspace(empty))));
  assert.deepEqual(snapshotWorkspace(emptyRestored), snapshotWorkspace(empty));
  const catalogState = structuredClone(empty);
  catalogState.workspaceUi.activeSection = 'catalogs';
  const catalogRestored = prepareWorkspace(await decodeWorkspace(await encodeWorkspace(snapshotWorkspace(catalogState))));
  assert.equal(catalogRestored.workspaceUi.activeSection, 'catalogs');
  console.log('Workspace checks passed: ZIP round trip, atlas geometry, views, zoom, selected links, camera, empty workspace and invalid files.');
} finally { await server.close(); }
